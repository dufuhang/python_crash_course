city = ['shanghai', 'beijing', 'hongkong', 'zhengzhou', 'new york']

print("******************original******************")
print(city)

print("******************sorted()******************")
print(sorted(city))

print("******************sorted(reverse=true)******************")
print(sorted(city, reverse=True))
print("******************original******************")
print(city)

print("******************reverse()******************")
print(city.reverse())
print("******************original******************")
print(city)

print("******************sort()******************")
print(city.sort())
